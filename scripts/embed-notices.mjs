// embed-notices.mjs — regenerates src/ui/notices.ts from THIRD-PARTY-NOTICES.md
// (single source of truth: the .md file; the .ts embed keeps the offline About
// dialog in sync with the shipped notices).
// Run after editing THIRD-PARTY-NOTICES.md:  node scripts/embed-notices.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const md = readFileSync(new URL('../THIRD-PARTY-NOTICES.md', import.meta.url), 'utf8');
const escaped = md.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const out = `// GENERATED by scripts/embed-notices.mjs from THIRD-PARTY-NOTICES.md — do not edit by hand.
// Rendered by the About dialog (offline app: embedded, never fetched).
export const NOTICES_TEXT = \`${escaped}\`;
`;
writeFileSync(new URL('../src/ui/notices.ts', import.meta.url), out);
console.log(`embed-notices: src/ui/notices.ts (${md.length} chars of notices)`);
