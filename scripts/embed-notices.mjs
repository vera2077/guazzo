// embed-notices.mjs — regenerates src/ui/notices.ts from THIRD-PARTY-NOTICES.md
// (single source of truth: the .md file; the .ts embed keeps the offline About
// dialog in sync with the shipped notices).
// Run after editing THIRD-PARTY-NOTICES.md:  node scripts/embed-notices.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const escape = (text) =>
  text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const md = readFileSync(new URL('../THIRD-PARTY-NOTICES.md', import.meta.url), 'utf8');
const out = `// GENERATED by scripts/embed-notices.mjs from THIRD-PARTY-NOTICES.md — do not edit by hand.
// Rendered by the About dialog (offline app: embedded, never fetched).
export const NOTICES_TEXT = \`${escape(md)}\`;
`;
writeFileSync(new URL('../src/ui/notices.ts', import.meta.url), out);

// AF6: the licence is shown in the About dialog too. Shipping LICENSE beside
// the exe assumes the recipient goes looking for it; the dialog cannot.
const licence = readFileSync(new URL('../LICENSE', import.meta.url), 'utf8');
const licenceOut = `// GENERATED by scripts/embed-notices.mjs from LICENSE — do not edit by hand.
// Rendered by the About dialog so the terms travel with the binary.
export const LICENCE_TEXT = \`${escape(licence)}\`;
`;
writeFileSync(new URL('../src/ui/licence.ts', import.meta.url), licenceOut);

// fail the build if the embedded licence lost the copyright holder
if (!/Copyright\s+©?\s*\d{4}\s+vera2077/.test(licence)) {
  throw new Error('embed-notices: LICENSE no longer names the copyright holder (vera2077)');
}
console.log(`embed-notices: src/ui/notices.ts (${md.length} chars) + src/ui/licence.ts (${licence.length} chars)`);
