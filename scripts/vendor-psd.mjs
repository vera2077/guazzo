// Regenerates app/vendor/ag-psd-bundle.js from the installed ag-psd package and
// stamps its version into a banner. The vendor copy is the ONLY third-party
// runtime code Pigment ships, so it must never be able to drift from the
// dependency declared in package.json without this script complaining.
// Run: node scripts/vendor-psd.mjs
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';

const cwd = process.cwd();
const BANNER = /^\/\* ag-psd ([0-9][0-9A-Za-z.\-]*)/;

async function findPackageDir() {
  // pnpm puts the real package under node_modules/.pnpm/ag-psd@<ver>/node_modules/ag-psd
  const pnpm = join(cwd, 'node_modules', '.pnpm');
  const entries = await readdir(pnpm).catch(() => []);
  const hit = entries.filter((e) => e.startsWith('ag-psd@')).sort().pop();
  if (hit) return join(pnpm, hit, 'node_modules', 'ag-psd');
  return join(cwd, 'node_modules', 'ag-psd');
}

const dir = await findPackageDir();
const meta = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
const bundle = await readFile(join(dir, 'dist', 'bundle.js'), 'utf8');
const version = meta.version;
const out = `/* ag-psd ${version} — bundled UMD (pako inlined); generated by scripts/vendor-psd.mjs */\n${bundle}`;
await writeFile(join(cwd, 'vendor', 'ag-psd-bundle.js'), out);
console.log(`vendored ag-psd ${version} (${out.length} bytes)`);

/** verifies the vendor copy carries the version we expect; used by the build */
export function assertVendorVersion(expected) {
  return readFile(join(cwd, 'vendor', 'ag-psd-bundle.js'), 'utf8').then((txt) => {
    const m = BANNER.exec(txt);
    if (!m) throw new Error('vendor/ag-psd-bundle.js has no version banner — run scripts/vendor-psd.mjs');
    if (m[1].trim() !== expected) {
      throw new Error(`vendor/ag-psd-bundle.js is ${m[1].trim()} but package.json wants ${expected} — run scripts/vendor-psd.mjs`);
    }
    return true;
  });
}
